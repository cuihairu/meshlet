//! SSH alias 配置分发（agent 侧）：把 mesh 节点渲染成 `~/.ssh/meshlet.conf`
//! 的 `Host <alias>` 块，供 `ssh <alias>` 直达对端 overlay VIP。
//!
//! 安全铁律（默认全关，显式开启才动用户 `~/.ssh`）：
//! - `[ssh_config_sync] enabled`（默认 **false**）：关 = 一个字节都不写；
//! - 开 = 只写 meshlet 专用 fragment `~/.ssh/meshlet.conf`（原子写、0600、
//!   幂等重写——每轮按期望主机表整文件重渲染，节点下线即块消失），
//!   **绝不改写用户 `~/.ssh/config` 的既有内容**；
//! - `[ssh_config_sync] manage_include`（默认 false）：开 = 检测
//!   `~/.ssh/config` 是否已 `Include meshlet.conf`，缺失才追加一行
//!   （追加前把原文件备份一次到 `config.meshlet.bak`，并保留原权限）；
//!   关 = 只写 fragment，状态文件标注 `manual_required` 提示手动加 Include。
//!
//! alias 来源（面板/文档同口径，`alias_source` 如实标注）：
//! hub 显式覆写（`hub-config`）> 节点真实主机名（`hostname`）>
//! meshlet peer name（`peer-name`）。hub 未下发 `ssh_config` 段时 agent 用
//! 本机默认自生成（主机名 + 自身 overlay VIP + 端口 22）。

use meshlet_network::SshConfigPlan;
use std::io::Write;
use std::path::{Path, PathBuf};

/// fragment 文件名（meshlet 专用，不与用户 config 混写）。
pub const FRAGMENT_NAME: &str = "meshlet.conf";
/// `~/.ssh/config` 首次被管理前的一次性备份名（存在即不覆盖）。
const INCLUDE_BACKUP_NAME: &str = "config.meshlet.bak";

/// 期望主机条目（已解析 alias 与来源）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SshHost {
    pub name: String,
    pub alias: String,
    pub address: std::net::Ipv4Addr,
    pub port: Option<u16>,
    pub user: Option<String>,
    pub alias_source: &'static str,
}

/// Include 行状态（面板/日志口径）。
#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize)]
#[serde(rename_all = "snake_case")]
pub enum IncludeState {
    /// 同步开关关闭（不检查、不写）。
    Off,
    /// `~/.ssh/config` 已含 Include 行（本来就有，或本 agent 追加过）。
    Present,
    /// 本 agent 追加了 Include 行（原文件已备份）。
    Managed,
    /// include 管理关 / 追加失败：需要手动加 `Include meshlet.conf`。
    ManualRequired,
}

/// 同步结果状态（落 `{state_dir}/ssh-sync.json`，本地面板只读展示）。
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize)]
pub struct SyncStatus {
    pub enabled: bool,
    pub manage_include: bool,
    pub include_state: IncludeState,
    /// fragment 路径（开关关时也为 `~/.ssh/meshlet.conf` 的预期路径，供文案）。
    pub fragment_path: String,
    /// 本轮期望主机表（关 = 空表）。
    pub hosts: Vec<StatusHost>,
    pub last_error: Option<String>,
}

/// 状态文件里的单主机行（面板直接渲染）。
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize)]
pub struct StatusHost {
    pub name: String,
    pub alias: String,
    pub address: String,
    pub port: u16,
    pub user: Option<String>,
    pub alias_source: String,
}

/// SSH Host 别名 sanitize（与 hub 共用 [`meshlet_network::ssh_alias`] 实现，
/// 两端口径不漂移）：保留大小写，非法字符转连字符，空名兜底 `node`。
pub fn sanitize_alias(name: &str) -> String {
    meshlet_network::ssh_alias::sanitize_alias(name)
}

/// alias 默认推导：主机名优先（真实主机名），缺省回落 peer name；
/// 返回 (alias, source)。
pub fn default_alias(name: &str, hostname: Option<&str>) -> (String, &'static str) {
    meshlet_network::ssh_alias::resolve_alias(name, hostname, None)
}

/// hub 下发段 → 期望主机表。alias 与来源（`hub-config` > `hostname` >
/// `peer-name`）由 hub 在计划里解析下发；agent 只做防御性 sanitize，来源
/// 缺省（旧服务端）标注 `peer-name`。
pub fn hosts_from_plan(plan: &SshConfigPlan) -> Vec<SshHost> {
    let hosts = plan
        .hosts
        .iter()
        .map(|h| SshHost {
            name: h.name.clone(),
            alias: sanitize_alias(&h.alias),
            address: h.address,
            port: h.port,
            user: h.user.clone(),
            alias_source: known_alias_source(h.alias_source.as_deref()),
        })
        .collect();
    dedupe_aliases(hosts)
}

/// 未知来源串（未来服务端新增枚举值）回落 `peer-name`，面板不显示乱码。
fn known_alias_source(raw: Option<&str>) -> &'static str {
    match raw {
        Some("hub-config") => "hub-config",
        Some("hostname") => "hostname",
        _ => "peer-name",
    }
}

/// 同名 alias 去重：按 (name, address) 排序后，重复 alias 依次追加 `-2`、
/// `-3`…保证 fragment 确定性且 Host 块唯一。
fn dedupe_aliases(mut hosts: Vec<SshHost>) -> Vec<SshHost> {
    hosts.sort_by(|a, b| (&a.name, a.address).cmp(&(&b.name, b.address)));
    let mut used: std::collections::BTreeMap<String, usize> = std::collections::BTreeMap::new();
    for h in &mut hosts {
        let count = used.entry(h.alias.clone()).or_insert(0);
        *count += 1;
        if *count > 1 {
            h.alias = format!("{}-{}", h.alias, count);
        }
    }
    hosts
}

/// 渲染 fragment：每主机一个 `Host <alias>` 块；端口缺省写 22（显式可读），
/// user 仅在下发时出现（不覆盖本地 ssh 默认）。
pub fn render_fragment(hosts: &[SshHost]) -> String {
    let mut out = String::new();
    out.push_str("# Generated by meshlet agent (ssh_config_sync). Do not edit.\n");
    out.push_str("# Managed hosts are distributed by the meshlet hub; blocks disappear when a node leaves the desired config.\n\n");
    for h in hosts {
        out.push_str(&format!(
            "# meshlet peer: {} ({})\n",
            h.name, h.alias_source
        ));
        out.push_str(&format!("Host {}\n", h.alias));
        out.push_str(&format!("  HostName {}\n", h.address));
        out.push_str(&format!("  Port {}\n", h.port.unwrap_or(22)));
        if let Some(user) = &h.user {
            out.push_str(&format!("  User {}\n", user));
        }
        out.push('\n');
    }
    out
}

/// fragment 路径（`<home>/.ssh/meshlet.conf`）。
pub fn fragment_path(home: &Path) -> PathBuf {
    home.join(".ssh").join(FRAGMENT_NAME)
}

/// ssh_config 路径。
fn ssh_config_path(home: &Path) -> PathBuf {
    home.join(".ssh").join("config")
}

/// `~/.ssh/config` 是否已 Include meshlet fragment（行首 token `Include`
/// 大小写不敏感 + 行内含 `meshlet.conf`）。文件缺失 = 未包含。
pub fn config_includes_fragment(config: &Path) -> bool {
    let Ok(text) = std::fs::read_to_string(config) else {
        return false;
    };
    text.lines().any(|line| {
        let mut tokens = line.trim_start().split_whitespace();
        tokens
            .next()
            .is_some_and(|t| t.eq_ignore_ascii_case("Include"))
            && line.to_ascii_lowercase().contains("meshlet.conf")
    })
}

/// 确保用户 config 含 `Include meshlet.conf`：已有 → `Present`；缺失 →
/// 先备份原文件一次（`config.meshlet.bak`，存在即不覆盖），再追加一行并
/// 保留原文件权限；config 不存在则新建（0600）。
fn ensure_include(config: &Path) -> (IncludeState, Option<String>) {
    if config_includes_fragment(config) {
        return (IncludeState::Present, None);
    }
    let metadata = std::fs::metadata(config).ok();
    if let Ok(existing) = std::fs::read_to_string(config) {
        let backup = config.with_file_name(INCLUDE_BACKUP_NAME);
        if !backup.exists() {
            if let Err(e) = std::fs::write(&backup, &existing) {
                return (
                    IncludeState::ManualRequired,
                    Some(format!("backup user ssh config: {e}")),
                );
            }
            if let Some(m) = &metadata {
                let _ = std::fs::set_permissions(&backup, m.permissions());
            }
        }
    }
    // 权限先于写入：既有文件保留原权限（备份后恢复）；新建文件落盘即 0600。
    if metadata.is_none() {
        // 先创建空文件（create true 的 append 打开也满足），再钉 0600。
        let _ = std::fs::File::create(config);
        let _ = set_mode(config, 0o600);
    }
    let mut file = match std::fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(config)
    {
        Ok(f) => f,
        Err(e) => {
            return (
                IncludeState::ManualRequired,
                Some(format!("open {}: {e}", config.display())),
            )
        }
    };
    if let Some(m) = &metadata {
        if let Err(e) = std::fs::set_permissions(config, m.permissions()) {
            return (
                IncludeState::ManualRequired,
                Some(format!("preserve ssh config permissions: {e}")),
            );
        }
    }
    // 与既有内容隔一个空行，避免贴着无换行的最后一行。
    if let Err(e) = writeln!(file, "\nInclude {FRAGMENT_NAME}") {
        return (
            IncludeState::ManualRequired,
            Some(format!("append Include line: {e}")),
        );
    }
    let _ = file.flush();
    (IncludeState::Managed, None)
}

/// 原子写 + 权限钉 0600：同目录临时文件写完 chmod 后 rename（进程崩半路也
/// 不会留下半个 fragment，更不会动到别人的文件）。
fn write_atomic_0600(path: &Path, content: &str) -> Result<(), String> {
    let dir = path
        .parent()
        .ok_or_else(|| "fragment path has no parent".to_string())?;
    let tmp = tempfile_name(dir);
    {
        let mut f =
            std::fs::File::create(&tmp).map_err(|e| format!("create {}: {e}", tmp.display()))?;
        f.write_all(content.as_bytes())
            .map_err(|e| format!("write {}: {e}", tmp.display()))?;
        set_mode(&tmp, 0o600)?;
    }
    std::fs::rename(&tmp, path).map_err(|e| {
        let _ = std::fs::remove_file(&tmp);
        format!("rename {}: {e}", path.display())
    })
}

fn tempfile_name(dir: &Path) -> PathBuf {
    let nanos = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_nanos())
        .unwrap_or(0);
    dir.join(format!(".meshlet.conf.tmp-{nanos}"))
}

#[cfg(unix)]
fn set_mode(path: &Path, mode: u32) -> Result<(), String> {
    use std::os::unix::fs::PermissionsExt;
    std::fs::set_permissions(path, std::fs::Permissions::from_mode(mode))
        .map_err(|e| format!("chmod {}: {e}", path.display()))
}

#[cfg(not(unix))]
fn set_mode(_path: &Path, _mode: u32) -> Result<(), String> {
    Ok(()) // Windows 无 POSIX 权限；ACL 继承用户目录默认
}

/// 本机主机名：Windows 取 `COMPUTERNAME`，其余走 `hostname` 命令；都失败为
/// `None`（回落 peer name）。trim 后为空同样视为 None。
pub fn local_hostname() -> Option<String> {
    let candidate = if cfg!(target_os = "windows") {
        std::env::var("COMPUTERNAME").ok()
    } else {
        std::process::Command::new("hostname")
            .output()
            .ok()
            .filter(|o| o.status.success())
            .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
    };
    candidate
        .map(|s| s.trim().to_string())
        .filter(|s| !s.is_empty())
}

/// 本机默认主机条目（hub 未下发时的自生成块）：主机名 > peer name。
pub fn self_host(name: &str, address: std::net::Ipv4Addr) -> SshHost {
    let (alias, source) = default_alias(name, local_hostname().as_deref());
    SshHost {
        name: name.to_string(),
        alias,
        address,
        port: None,
        user: None,
        alias_source: source,
    }
}

/// 每轮同步入口（tick 调用；失败只记状态不打断数据面循环）。
///
/// - 开关关：只刷新状态文件（enabled=false），**不碰 `~/.ssh` 任何文件**；
/// - 开：按期望主机表整文件重渲染 fragment（幂等：内容不变不重写），
///   再按 `manage_include` 决定是否管理用户 config 的 Include 行。
pub fn sync(
    home: &Path,
    hosts: Option<&[SshHost]>,
    fallback: &SshHost,
    enabled: bool,
    manage_include: bool,
    status_path: &Path,
) -> SyncStatus {
    let fragment = fragment_path(home);
    let mut status = SyncStatus {
        enabled,
        manage_include,
        include_state: if enabled && manage_include {
            IncludeState::ManualRequired
        } else {
            IncludeState::Off
        },
        fragment_path: fragment.display().to_string(),
        hosts: Vec::new(),
        last_error: None,
    };
    if !enabled {
        write_status(status_path, &status);
        return status;
    }
    let desired: Vec<SshHost> = match hosts {
        Some(list) => dedupe_aliases(list.to_vec()),
        None => vec![fallback.clone()],
    };
    status.hosts = desired
        .iter()
        .map(|h| StatusHost {
            name: h.name.clone(),
            alias: h.alias.clone(),
            address: h.address.to_string(),
            port: h.port.unwrap_or(22),
            user: h.user.clone(),
            alias_source: h.alias_source.to_string(),
        })
        .collect();
    match write_fragment(&fragment, &desired) {
        Ok(()) => {}
        Err(e) => {
            status.last_error = Some(e);
            write_status(status_path, &status);
            return status;
        }
    }
    if manage_include {
        let config = ssh_config_path(home);
        let (state, error) = ensure_include(&config);
        status.include_state = state;
        status.last_error = error;
    } else {
        status.include_state = IncludeState::ManualRequired;
    }
    write_status(status_path, &status);
    status
}

fn write_fragment(fragment: &Path, hosts: &[SshHost]) -> Result<(), String> {
    let content = render_fragment(hosts);
    let dir = fragment
        .parent()
        .ok_or_else(|| "fragment path has no parent".to_string())?;
    // ~/.ssh 不存在则创建（0700）；已存在不动权限（尊重用户自有设置）。
    if !dir.exists() {
        std::fs::create_dir_all(dir).map_err(|e| format!("create {}: {e}", dir.display()))?;
        let _ = set_mode(dir, 0o700);
    }
    // 幂等：内容一致不重写（mtime 稳定，同步监控/备份不被打搅）。
    if let Ok(existing) = std::fs::read_to_string(fragment) {
        if existing == content {
            let meta = std::fs::metadata(fragment)
                .map_err(|e| format!("stat {}: {e}", fragment.display()))?;
            #[cfg(unix)]
            {
                use std::os::unix::fs::PermissionsExt;
                if meta.permissions().mode() & 0o777 != 0o600 {
                    set_mode(fragment, 0o600)?;
                }
            }
            return Ok(());
        }
    }
    write_atomic_0600(fragment, &content)
}

fn write_status(status_path: &Path, status: &SyncStatus) {
    match serde_json::to_string_pretty(status) {
        Ok(body) => {
            if let Some(parent) = status_path.parent() {
                let _ = std::fs::create_dir_all(parent);
            }
            let tmp = status_path.with_extension("json.tmp");
            if std::fs::write(&tmp, body).is_ok() {
                let _ = std::fs::rename(&tmp, status_path);
            }
        }
        Err(_) => {} // 状态文件尽力而为：失败不影响数据面，也不重试
    }
}

/// `{state_dir}/ssh-sync.json` 路径。
pub fn status_path(state_dir: &str) -> PathBuf {
    Path::new(state_dir).join("ssh-sync.json")
}

